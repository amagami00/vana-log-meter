#!/usr/bin/env python3
"""CP932 の 2 バイト文字の変換表を Dart のコードとして書き出す。

使い方: python3 -I tool/gen_cp932_table.py > lib/src/cp932_table.dart

Python 標準の cp932 コーデック（Microsoft の CP932 表）を正とする。
先行バイトごとに、2 バイト目 0x40〜0xFC（189 通り）に対応する文字を
1 本の文字列に並べる。対応のない位置は U+FFFD にする。
"""

LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAIL_FIRST, TRAIL_LAST = 0x40, 0xFC


def dart_escape(ch: str) -> str:
    cp = ord(ch)
    if ch in "\\'$":
        return "\\" + ch
    if cp < 0x20 or cp == 0x7F or 0xD800 <= cp <= 0xDFFF:
        return "\\u{%x}" % cp
    if cp > 0xFFFF:
        return "\\u{%x}" % cp
    return ch


def main() -> None:
    out = [
        "// GENERATED by tool/gen_cp932_table.py. Do not edit.",
        "//",
        "// CP932 の 2 バイト文字。キーは先行バイト、値は 2 バイト目",
        "// 0x40〜0xFC に対応する文字を順に並べた文字列（未定義は U+FFFD）。",
        "",
        "const int cp932TrailFirst = 0x%02X;" % TRAIL_FIRST,
        "const int cp932TrailLast = 0x%02X;" % TRAIL_LAST,
        "",
        "const Map<int, String> cp932DoubleByte = {",
    ]
    for lead in LEADS:
        chars = []
        for trail in range(TRAIL_FIRST, TRAIL_LAST + 1):
            try:
                ch = bytes([lead, trail]).decode("cp932")
                if len(ch) != 1:
                    ch = "�"
            except UnicodeDecodeError:
                ch = "�"
            chars.append(dart_escape(ch))
        out.append("  0x%02X: '%s'," % (lead, "".join(chars)))
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
